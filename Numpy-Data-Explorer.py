import numpy as np
import time
print("🔹 Array Creation")
arr1 = np.array([1, 2, 3, 4, 5])
arr2 = np.arange(10)
arr3 = np.linspace(0, 1, 5)
print("arr1:", arr1)
print("arr2:", arr2)
print("arr3:", arr3)
print("\n🔹 Indexing & Slicing")
print("First element:", arr1[0])
print("Last element:", arr1[-1])
print("Slice (1 to 3):", arr1[1:4])
print("\n🔹 Mathematical Operations")
print("Addition:", arr1 + 2)
print("Multiplication:", arr1 * 3)
print("Square:", arr1 ** 2)
print("\n🔹 Statistical Operations")
print("Mean:", np.mean(arr1))
print("Sum:", np.sum(arr1))
print("Max:", np.max(arr1))
print("Min:", np.min(arr1))
print("\n🔹 Axis-wise Operations")
matrix = np.array([[1, 2, 3], [4, 5, 6]])
print("Matrix:\n", matrix)
print("Sum (axis=0):", np.sum(matrix, axis=0))  # column-wise
print("Sum (axis=1):", np.sum(matrix, axis=1))  # row-wise
print("\n🔹 Reshaping")
reshaped = arr2.reshape(2, 5)
print("Reshaped (2x5):\n", reshaped)
print("\n🔹 Broadcasting")
matrix2 = np.array([[1, 2, 3], [4, 5, 6]])
vector = np.array([10, 20, 30])
print("Broadcast Add:\n", matrix2 + vector)
print("\n🔹 Save & Load")
np.save("array_data.npy", arr1)
loaded = np.load("array_data.npy")
print("Loaded Array:", loaded)
print("\n🔹 Performance Comparison")
py_list = list(range(1000000))
start = time.time()
py_result = [x * 2 for x in py_list]
end = time.time()
print("Python List Time:", end - start)
np_array = np.arange(1000000)
start = time.time()
np_result = np_array * 2
end = time.time()
print("NumPy Array Time:", end - start)
print("\n NumPy is faster than Python lists for large data!")
